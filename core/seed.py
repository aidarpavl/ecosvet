def grid_points(box, n):
    x1, y1, x2, y2 = box
    w, h = x2 - x1, y2 - y1
    if n <= 0:
        return []
    cols = max(1, round(math.sqrt(n * w / max(h, 1))))
    rows = math.ceil(n / cols)
    pts = []
    for i in range(n):
        r, c = divmod(i, cols)
        in_row = min(cols, n - r * cols)
        px = x1 + w * (c + 0.5) / in_row
        py = y1 + h * (r + 0.5) / rows
        pts.append((round(px, 1), round(py, 1)))
    return pts


def seed() -> None:
    for name, tech, w, lm, life, price in LAMP_CATALOG:
        db.upsert_lamp_type({"name": name, "tech": tech, "watts": w, "lumens": lm, "life_hours": life, "price": price})
    for rt, lux in NORMS.items():
        db.set_norm(rt, lux)
    types = {t["name"]: t for t in db.lamp_types()}
    db.set_setting("led_default", types["LED-панель 36 Вт 600×600"]["id"])
    db.set_setting("led_small", types["LED-лампа 12 Вт E27"]["id"])
    db.set_setting("led_highbay", types["LED спортивный 100 Вт IP65"]["id"])
    s = db.get_settings()
    u, mf = float(s["util_factor"]), float(s["maint_factor"])

    for i, (code, name, path) in enumerate(MAPS):
        map_id = db.add_map(code, name, path, i)
        for rname, rtype, box, area, windows, extra in ROOMS[code]:
            if area is None:
                area = round((box[2] - box[0]) * (box[3] - box[1]) * SCALE[code], 1)
            room_id = db.add_room({
                "map_id": map_id, "name": rname, "room_type": rtype,
                "x1": box[0], "y1": box[1], "x2": box[2], "y2": box[3], "area": area, "height": 3.0,
                "windows": windows, "hours_per_day": HOURS.get(rtype, 6), "days_per_month": 22,
                "months_per_year": 9, "has_sensor": 0,
                "note": "Данные ориентировочные — уточните при обходе",
            })
            lt = types[extra.get("lamp", DEFAULT_LAMP[rtype])]
            need = lamps_needed(NORMS[rtype], area, lt["lumens"], u, mf)
            n = max(1, round(need * extra.get("f", 1.0)))
            for x, y in grid_points(box, n):
                db.add_lamp(map_id, room_id, lt["id"], x, y, 1)


def ensure_seed() -> None:
    if db.init_db():
        seed()
