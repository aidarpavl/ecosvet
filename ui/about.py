import streamlit as st

from core.swot import RULES


def render():
    st.markdown("""
## ℹ️ О проекте «ЭкоСвет»

**Тема:** «ЭкоСвет: как уменьшить расход электроэнергии в школе».
**Практическая ценность:** проведение школьного энергоаудита, выявление источников нерационального
потребления электроэнергии и разработка правил энергосбережения.

### 🔍 Методика энергоаудита
1. **Подготовка.** Планы этажей (эвакуационные планы), перечень помещений, тариф на электроэнергию.
2. **Обход.** В каждом помещении записать: тип и количество светильников, мощность (по маркировке), площадь,
   время работы освещения, наличие окон и датчиков.
3. **Ввод данных.** «Карты школы» → карандашом ставим лампы; «Паспорт кабинета» → площадь, режим работы.
4. **Анализ.** Освещённость против нормы, удельная мощность, ТОП потребителей, доля устаревших ламп.
5. **Сценарии экономии.** LED, датчики, дневной свет, поведение; инвестиции и окупаемость.
6. **SWOT и рекомендации.** Правила энергосбережения, план действий.
7. **Обратная связь.** Ученики и учителя оставляют отзывы, администрация отвечает.

### 📐 Формулы
| Показатель | Формула |
|---|---|
| Мощность помещения | P = Σ(Wᵢ·nᵢ), Вт; P(кВт) = P/1000 |
| Световой поток | Φ = Σ(Φᵢ·nᵢ), лм |
| Средняя освещённость | E = Φ·U·MF / S, лк |
| Ламп до нормы | N = ⌈E_норм·S / (Φ_лампы·U·MF)⌉ |
| Потребление | W = P(кВт) × часы/день × дни/мес × мес/год |
| Стоимость | C = W × тариф (₸/кВт·ч) |
| Выбросы CO₂ | CO₂ = W × k_сети |
| Класс эффективности | Вт/м² на 100 лк: A ≤ 3; B ≤ 4,5; C ≤ 6; D ≤ 8; E > 8 |

U — коэффициент использования светового потока (≈0,5 для типового класса), MF — коэффициент эксплуатации (≈0,8).
Это упрощённая инженерная оценка; точная освещённость измеряется люксметром на рабочих местах.

### 👥 Роли
- **Администратор** — редактирует карты, помещения, лампы, тарифы, нормы, SWOT; отвечает на отзывы.
- **Пользователь** — после регистрации просматривает все данные и оставляет отзывы.
""")
    st.markdown("### 📜 Правила энергосбережения школы")
    for i, r in enumerate(RULES, 1):
        st.markdown(f"{i}. {r}")
    st.download_button("⬇️ Скачать правила (для печати)",
                       ("ПРАВИЛА ЭНЕРГОСБЕРЕЖЕНИЯ ШКОЛЫ «ЭкоСвет»\n\n" +
                        "\n".join(f"{i}. {r}" for i, r in enumerate(RULES, 1))).encode("utf-8"),
                       "ecosvet_rules.txt", "text/plain")
